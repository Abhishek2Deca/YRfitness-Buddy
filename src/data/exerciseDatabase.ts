// Helper to create consistent detailed steps
function createSteps(
  setupText: string,
  setupHighlight: string,
  bodyText: string,
  moveText: string
): [SetupStep, SetupStep, SetupStep] {
  return [
    {
      title: 'Setup & Grip:',
      text: setupText,
      highlight: setupHighlight,
    },
    {
      title: 'Body Foundation:',
      text: bodyText,
    },
    {
      title: 'Movement & Tempo:',
      text: moveText,
    },
  ];
}

